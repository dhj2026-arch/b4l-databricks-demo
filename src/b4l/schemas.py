def ddl(columns: list[Column]) -> str:
    """Spark DDL schema string including column comments."""
    parts = []
    for name, dtype, comment in columns:
        escaped = comment.replace("'", "\\'")
        parts.append(f"{name} {dtype} COMMENT '{escaped}'")
    return ", ".join(parts)


def column_names(columns: list[Column]) -> list[str]:
    return [c[0] for c in columns]
